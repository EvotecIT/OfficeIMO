using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace OfficeIMO.Yaml.SourceGeneration;

/// <summary>
/// Writes the context's partial class: a <c>Default</c> instance, constructors, one <c>YamlTypeInfo&lt;T&gt;</c> property
/// per type, and the <c>CreateTypeInfo</c> override that builds metadata through <c>YamlMetadataServices</c>.
/// </summary>
internal static class YamlContextEmitter {
    private const string Services = "global::OfficeIMO.Yaml.YamlMetadataServices";
    private const string Options = "global::OfficeIMO.Yaml.YamlSerializerOptions";
    private const string Unsafe = "global::System.Runtime.CompilerServices.Unsafe";
    private const string UnsafeAccessor = "global::System.Runtime.CompilerServices.UnsafeAccessor";
    private const string UnsafeAccessorKind = "global::System.Runtime.CompilerServices.UnsafeAccessorKind";

    public static string Emit(INamedTypeSymbol context, List<YamlTypeEntry> entries, List<YamlTypeEntry> roots, bool unsafeAccessor) {
        AssignPropertyNames(context, entries);
        var text = new StringBuilder(4096);
        text.AppendLine("// <auto-generated/>");
        text.AppendLine("#nullable enable annotations");
        text.AppendLine("#nullable disable warnings");
        text.AppendLine("#pragma warning disable CS0612, CS0618");
        text.AppendLine();
        string? ns = context.ContainingNamespace.IsGlobalNamespace ? null : context.ContainingNamespace.ToDisplayString();
        if (ns is not null) text.Append("namespace ").AppendLine(ns).AppendLine("{");

        var containers = new List<INamedTypeSymbol>();
        for (INamedTypeSymbol? outer = context.ContainingType; outer is not null; outer = outer.ContainingType) containers.Insert(0, outer);
        foreach (INamedTypeSymbol outer in containers) text.Append("partial ").Append(Keyword(outer)).Append(' ').AppendLine(outer.Name).AppendLine("{");

        string name = context.Name;
        text.Append("partial class ").AppendLine(name).AppendLine("{");
        text.AppendLine("    /// <summary>Gets a context bound to new default options.</summary>");
        text.Append("    public static ").Append(name).Append(" Default { get; } = new ").Append(name).Append("(new ").Append(Options).AppendLine("());");
        text.AppendLine();
        text.AppendLine("    /// <summary>Creates a context bound to new default options.</summary>");
        text.Append("    public ").Append(name).AppendLine("() : base(null) { }");
        text.AppendLine();
        text.AppendLine("    /// <summary>Creates a context bound to the given options, which it makes use this context's metadata.</summary>");
        text.Append("    public ").Append(name).Append('(').Append(Options).AppendLine(" options) : base(options) { }");

        var accessors = new StringBuilder();
        foreach (YamlTypeEntry entry in entries) {
            if (entry.Shape == YamlShape.BuiltIn && !roots.Contains(entry)) continue;
            string info = "global::OfficeIMO.Yaml.YamlTypeInfo<" + entry.FullName + ">";
            text.AppendLine();
            text.Append("    private ").Append(info).Append("? _").Append(entry.PropertyName).AppendLine(";");
            text.Append("    /// <summary>Gets the YAML metadata for ").Append(Escape(entry.Type.ToDisplayString())).AppendLine(".</summary>");
            text.Append("    ").Append(IsPublic(entry.Type) ? "public " : "internal ").Append(info).Append(' ').Append(entry.PropertyName)
                .Append(" => _").Append(entry.PropertyName).Append(" ??= (").Append(info).Append(")Options.GetTypeInfo(typeof(").Append(entry.FullName).AppendLine("));");
        }

        text.AppendLine();
        text.AppendLine("    /// <inheritdoc />");
        text.Append("    protected override global::OfficeIMO.Yaml.YamlTypeInfo? CreateTypeInfo(global::System.Type type, ").Append(Options).AppendLine(" options)");
        text.AppendLine("    {");
        foreach (YamlTypeEntry entry in entries) {
            if (entry.Shape == YamlShape.BuiltIn) continue;
            text.Append("        if (type == typeof(").Append(entry.FullName).Append(")) return Create_").Append(entry.PropertyName).AppendLine("(options);");
        }
        text.AppendLine("        return null;");
        text.AppendLine("    }");

        foreach (YamlTypeEntry entry in entries) {
            if (entry.Shape == YamlShape.BuiltIn) continue;
            text.AppendLine();
            text.Append("    private static global::OfficeIMO.Yaml.YamlTypeInfo<").Append(entry.FullName).Append("> Create_").Append(entry.PropertyName)
                .Append('(').Append(Options).AppendLine(" options)");
            text.AppendLine("    {");
            EmitCreate(text, entry, accessors, unsafeAccessor);
            text.AppendLine("    }");
        }
        if (accessors.Length > 0) text.AppendLine().Append(accessors.ToString());

        text.AppendLine("}");
        foreach (INamedTypeSymbol _ in containers) text.AppendLine("}");
        if (ns is not null) text.AppendLine("}");
        return text.ToString();
    }

    private static void EmitCreate(StringBuilder text, YamlTypeEntry entry, StringBuilder accessors, bool unsafeAccessor) {
        string type = entry.FullName;
        string element = entry.Element?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) ?? string.Empty;
        switch (entry.Shape) {
            case YamlShape.Nullable:
                text.Append("        return ").Append(Services).Append(".CreateNullableInfo<").Append(element).AppendLine(">(options);");
                return;
            case YamlShape.Enum:
                text.Append("        return ").Append(Services).Append(".CreateEnumInfo<").Append(type).AppendLine(">(options);");
                return;
            case YamlShape.Array:
                text.Append("        return ").Append(Services).Append(".CreateCollectionInfo<").Append(type).Append(", ").Append(element)
                    .AppendLine(">(options, static list => list.ToArray());");
                return;
            case YamlShape.List:
                text.Append("        return ").Append(Services).Append(".CreateCollectionInfo<").Append(type).Append(", ").Append(element)
                    .AppendLine(">(options, static list => list);");
                return;
            case YamlShape.Set:
                text.Append("        return ").Append(Services).Append(".CreateCollectionInfo<").Append(type).Append(", ").Append(element)
                    .Append(">(options, static list => new global::System.Collections.Generic.HashSet<").Append(element).AppendLine(">(list));");
                return;
            case YamlShape.CustomCollection:
                text.Append("        return ").Append(Services).Append(".CreateCollectionInfo<").Append(type).Append(", ").Append(element).AppendLine(">(options, static list =>");
                text.AppendLine("        {");
                text.Append("            var collection = new ").Append(type).AppendLine("();");
                text.Append("            var target = (global::System.Collections.Generic.ICollection<").Append(element).AppendLine(">)collection;");
                text.AppendLine("            foreach (var item in list) target.Add(item);");
                text.AppendLine("            return collection;");
                text.AppendLine("        });");
                return;
            case YamlShape.Dictionary:
            case YamlShape.CustomDictionary: {
                string key = entry.Key!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                string value = entry.Value!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                text.Append("        return ").Append(Services).Append(".CreateDictionaryInfo<").Append(type).Append(", ").Append(key).Append(", ").Append(value).Append(">(options, static dictionary");
                if (entry.Shape == YamlShape.Dictionary) {
                    text.AppendLine(" => dictionary);");
                    return;
                }
                text.AppendLine(" =>");
                text.AppendLine("        {");
                text.Append("            var result = new ").Append(type).AppendLine("();");
                text.Append("            var target = (global::System.Collections.Generic.IDictionary<").Append(key).Append(", ").Append(value).AppendLine(">)result;");
                text.AppendLine("            foreach (var pair in dictionary) target.Add(pair.Key, pair.Value);");
                text.AppendLine("            return result;");
                text.AppendLine("        });");
                return;
            }
            case YamlShape.Object:
                EmitObject(text, entry, accessors, unsafeAccessor);
                return;
        }
    }

    private static void EmitObject(StringBuilder text, YamlTypeEntry entry, StringBuilder accessors, bool unsafeAccessor) {
        string type = entry.FullName;
        YamlObjectShape shape = entry.Object!;
        var named = (INamedTypeSymbol)entry.Type;
        bool isStruct = named.IsValueType;
        text.Append("        var values = new global::OfficeIMO.Yaml.YamlObjectInfoValues<").Append(type).AppendLine(">");
        text.AppendLine("        {");

        IMethodSymbol? constructor = shape.Constructor;
        bool setsRequired = constructor is not null && constructor.GetAttributes().Any(static a => a.AttributeClass?.ToDisplayString() == "System.Diagnostics.CodeAnalysis.SetsRequiredMembersAttribute");
        if (shape.UseDefault) {
            text.Append("            ObjectCreator = static () => ")
                .Append(shape.HasRequiredMembers ? "global::System.Activator.CreateInstance<" + type + ">()" : "new " + type + "()").AppendLine(",");
        } else if (constructor is not null) {
            text.Append("            ObjectWithParameterizedConstructorCreator = static args => ");
            var arguments = new StringBuilder();
            for (int i = 0; i < constructor.Parameters.Length; i++) {
                if (i > 0) arguments.Append(", ");
                arguments.Append('(').Append(constructor.Parameters[i].Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append(")args[")
                    .Append(i.ToString(CultureInfo.InvariantCulture)).Append(']');
            }
            if (shape.HasRequiredMembers && !setsRequired) {
                if (unsafeAccessor) {
                    string creator = "__Create_" + entry.PropertyName;
                    text.Append(creator).Append('(').Append(arguments).AppendLine("),");
                    accessors.Append("    [").Append(UnsafeAccessor).Append('(').Append(UnsafeAccessorKind).AppendLine(".Constructor)]");
                    accessors.Append("    private static extern ").Append(type).Append(' ').Append(creator).Append('(');
                    for (int i = 0; i < constructor.Parameters.Length; i++) {
                        if (i > 0) accessors.Append(", ");
                        accessors.Append(constructor.Parameters[i].Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append(" a").Append(i.ToString(CultureInfo.InvariantCulture));
                    }
                    accessors.AppendLine(");");
                } else {
                    text.Append("(").Append(type).Append(")global::System.Activator.CreateInstance(typeof(").Append(type).AppendLine("), args)!,");
                }
            } else {
                text.Append("new ").Append(type).Append('(').Append(arguments).AppendLine("),");
            }
            text.AppendLine("            ConstructorParameterMetadataInitializer = static () => new global::OfficeIMO.Yaml.YamlParameterInfoValues[]");
            text.AppendLine("            {");
            for (int i = 0; i < constructor.Parameters.Length; i++) {
                IParameterSymbol parameter = constructor.Parameters[i];
                text.Append("                new global::OfficeIMO.Yaml.YamlParameterInfoValues { Name = ").Append(SymbolDisplay.FormatLiteral(parameter.Name, true))
                    .Append(", ParameterType = typeof(").Append(parameter.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append("), Position = ")
                    .Append(i.ToString(CultureInfo.InvariantCulture)).Append(", DefaultValue = ").Append(DefaultValue(parameter)).AppendLine(" },");
            }
            text.AppendLine("            },");
        }

        text.AppendLine("            PropertyMetadataInitializer = static options => new global::OfficeIMO.Yaml.YamlPropertyInfo[]");
        text.AppendLine("            {");
        int index = 0;
        foreach (YamlPropertyShape property in shape.Properties) {
            IPropertySymbol symbol = property.Symbol;
            string propertyType = symbol.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            string member = Identifier(symbol.Name);
            text.Append("                ").Append(Services).Append(".CreatePropertyInfo<").Append(propertyType).Append(">(options, new global::OfficeIMO.Yaml.YamlPropertyInfoValues<")
                .Append(propertyType).AppendLine(">");
            text.AppendLine("                {");
            text.Append("                    Name = ").Append(SymbolDisplay.FormatLiteral(symbol.Name, true)).AppendLine(",");
            if (property.YamlName is not null) text.Append("                    YamlName = ").Append(SymbolDisplay.FormatLiteral(property.YamlName, true)).AppendLine(",");
            if (property.IsRequired) text.AppendLine("                    IsRequired = true,");
            if (property.IgnoreCondition is not null) text.Append("                    IgnoreCondition = global::OfficeIMO.Yaml.YamlIgnoreCondition.").Append(property.IgnoreCondition).AppendLine(",");
            text.Append("                    Getter = static obj => ((").Append(type).Append(")obj).").Append(member).AppendLine(",");
            switch (property.Setter) {
                case YamlSetter.Direct:
                    text.Append("                    Setter = static (obj, value) => ")
                        .Append(isStruct ? Unsafe + ".Unbox<" + type + ">(obj)" : "((" + type + ")obj)").Append('.').Append(member).AppendLine(" = value,");
                    break;
                case YamlSetter.Accessor: {
                    INamedTypeSymbol declaring = symbol.SetMethod!.ContainingType;
                    string declaringName = declaring.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                    string accessor = "__Set_" + entry.PropertyName + "_" + index.ToString(CultureInfo.InvariantCulture);
                    text.Append("                    Setter = static (obj, value) => ").Append(accessor).Append('(')
                        .Append(isStruct ? "ref " + Unsafe + ".Unbox<" + type + ">(obj)" : "(" + declaringName + ")(" + type + ")obj").AppendLine(", value),");
                    accessors.Append("    [").Append(UnsafeAccessor).Append('(').Append(UnsafeAccessorKind).Append(".Method, Name = ")
                        .Append(SymbolDisplay.FormatLiteral(symbol.SetMethod.Name, true)).AppendLine(")]");
                    accessors.Append("    private static extern void ").Append(accessor).Append('(').Append(isStruct ? "ref " + type : declaringName)
                        .Append(" obj, ").Append(propertyType).AppendLine(" value);");
                    break;
                }
                case YamlSetter.Reflection: {
                    INamedTypeSymbol declaring = symbol.SetMethod!.ContainingType;
                    string field = "__Property_" + entry.PropertyName + "_" + index.ToString(CultureInfo.InvariantCulture);
                    text.Append("                    Setter = static (obj, value) => ").Append(field).AppendLine(".SetValue(obj, value),");
                    accessors.Append("    private static readonly global::System.Reflection.PropertyInfo ").Append(field).Append(" = typeof(")
                        .Append(declaring.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append(").GetProperty(").Append(SymbolDisplay.FormatLiteral(symbol.Name, true))
                        .AppendLine(", global::System.Reflection.BindingFlags.Public | global::System.Reflection.BindingFlags.Instance | global::System.Reflection.BindingFlags.DeclaredOnly)!;");
                    break;
                }
            }
            text.AppendLine("                }),");
            index++;
        }
        text.AppendLine("            },");

        if (shape.Derived.Count > 0) {
            text.AppendLine("            DerivedTypes = new global::OfficeIMO.Yaml.YamlDerivedTypeAttribute[]");
            text.AppendLine("            {");
            foreach ((ITypeSymbol derived, string discriminator) in shape.Derived) {
                text.Append("                new global::OfficeIMO.Yaml.YamlDerivedTypeAttribute(typeof(").Append(derived.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                    .Append("), ").Append(SymbolDisplay.FormatLiteral(discriminator, true)).AppendLine("),");
            }
            text.AppendLine("            },");
            if (shape.DiscriminatorPropertyName is not null) {
                text.Append("            DiscriminatorPropertyName = ").Append(SymbolDisplay.FormatLiteral(shape.DiscriminatorPropertyName, true)).AppendLine(",");
            }
        }
        text.AppendLine("        };");
        text.Append("        return ").Append(Services).Append(".CreateObjectInfo<").Append(type).AppendLine(">(options, values);");
    }

    /// <summary>The value a missing constructor argument takes: its default value, or the type's default.</summary>
    private static string DefaultValue(IParameterSymbol parameter) {
        ITypeSymbol type = parameter.Type;
        string name = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        bool nullableValue = type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T };
        if (!parameter.HasExplicitDefaultValue || parameter.ExplicitDefaultValue is null) {
            return type.IsValueType && !nullableValue ? "(object)default(" + name + ")" : "null";
        }
        object value = parameter.ExplicitDefaultValue;
        ITypeSymbol valueType = nullableValue ? ((INamedTypeSymbol)type).TypeArguments[0] : type;
        string literal = value switch {
            string text => SymbolDisplay.FormatLiteral(text, true),
            char character => SymbolDisplay.FormatLiteral(character, true),
            bool flag => flag ? "true" : "false",
            double number when double.IsNaN(number) => "double.NaN",
            double number when double.IsPositiveInfinity(number) => "double.PositiveInfinity",
            double number when double.IsNegativeInfinity(number) => "double.NegativeInfinity",
            float number when float.IsNaN(number) => "float.NaN",
            float number when float.IsPositiveInfinity(number) => "float.PositiveInfinity",
            float number when float.IsNegativeInfinity(number) => "float.NegativeInfinity",
            IFormattable number => number.ToString(null, CultureInfo.InvariantCulture),
            _ => value.ToString() ?? "null"
        };
        if (value is string) return literal;
        return "(object)(" + valueType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ")(" + literal + ")";
    }

    private static void AssignPropertyNames(INamedTypeSymbol context, List<YamlTypeEntry> entries) {
        var used = new HashSet<string>(StringComparer.Ordinal) { "Default", "Options", "GetTypeInfo", "CreateTypeInfo", context.Name };
        foreach (ISymbol member in context.GetMembers()) used.Add(member.Name);
        foreach (YamlTypeEntry entry in entries) {
            string name = BaseName(entry.Type);
            string candidate = name;
            for (int i = 2; !used.Add(candidate); i++) candidate = name + i.ToString(CultureInfo.InvariantCulture);
            entry.PropertyName = candidate;
        }
    }

    private static string BaseName(ITypeSymbol type) {
        switch (type) {
            case IArrayTypeSymbol array:
                return BaseName(array.ElementType) + "Array";
            case INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable:
                return "Nullable" + BaseName(nullable.TypeArguments[0]);
            case INamedTypeSymbol named:
                var text = new StringBuilder(named.SpecialType != SpecialType.None ? named.MetadataName : named.Name);
                foreach (ITypeSymbol argument in named.TypeArguments) text.Append(BaseName(argument));
                return text.ToString();
            default:
                return "Type";
        }
    }

    private static bool IsPublic(ITypeSymbol type) {
        switch (type) {
            case IArrayTypeSymbol array:
                return IsPublic(array.ElementType);
            case INamedTypeSymbol named:
                for (INamedTypeSymbol? current = named; current is not null; current = current.ContainingType) {
                    if (current.DeclaredAccessibility != Accessibility.Public) return false;
                }
                foreach (ITypeSymbol argument in named.TypeArguments) {
                    if (!IsPublic(argument)) return false;
                }
                return true;
            default:
                return true;
        }
    }

    private static string Keyword(INamedTypeSymbol type) => type.TypeKind switch {
        TypeKind.Struct => type.IsRecord ? "record struct" : "struct",
        TypeKind.Interface => "interface",
        _ => type.IsRecord ? "record" : "class"
    };

    private static string Identifier(string name) =>
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

    private static string Escape(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
