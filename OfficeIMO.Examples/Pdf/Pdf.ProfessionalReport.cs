using OfficeIMO.Drawing;
using OfficeIMO.Pdf;
using System.IO;

namespace OfficeIMO.Examples.Pdf {
    internal static class ProfessionalReportPdf {
        public static void Example_Pdf_ProfessionalReport(string folderPath, bool open = false) {
            string path = Path.Combine(folderPath, "Pdf.ProfessionalReport.pdf");
            string imagePath = Path.Combine(AppContext.BaseDirectory, "Images", "EvotecLogo.png");
            byte[] logoBytes = File.Exists(imagePath) ? File.ReadAllBytes(imagePath) : CreateFallbackLogo();

            OfficeThemePalette palette = OfficeTheme.Default.Palette;
            PdfDocument.Create(pdf => pdf.Content(content => content
                .Row(row => row.Gap(OfficeLength.Points(12))
                    .PercentColumn(72, column => column.Title("Executive security summary"))
                    .PercentColumn(28, column => column.AddImage(logoBytes, OfficeLength.Points(120), OfficeLength.Points(48), OfficeAlignment.Right, fit: OfficeImageFit.Contain)))
                .AddParagraph(p => {
                    p.AddText("A first-party PDF report built with ");
                    p.AddText("OfficeIMO.Pdf").SetBold();
                    p.AddText(", shared drawing descriptors, wrapped tables, images, and generated bookmarks.");
                })
                .AddPanelParagraph(
                    p => { p.AddText("Healthy").SetBold().SetColor(palette.Success); p.AddText(" posture with no critical findings."); },
                    CreateStatusPanelStyle(palette))
                .AddPanelParagraph(
                    p => p.AddText("Operator note: long values should wrap cleanly, tables should stay inside the page, and reusable drawing primitives should remain available to Word, Excel, PowerPoint, and PDF exporters."),
                    style: null)
                .AddTable(new[] {
                    new[] { "Signal", "Evidence", "Action" },
                    new[] { "DMARC", "Policy is enforced for the primary domain and aligned subdomains.", "Monitor" },
                    new[] { "TLS", "Certificate chain and protocol posture are ready for automated PSWriteOffice reports.", "Keep" },
                    new[] { "DNS", "Delegation and stale-record checks are summarized without overflowing table cells.", "Review" },
                    new[] { "PDF", "The report is generated by the MIT licensed dependency-free OfficeIMO.Pdf engine.", "Expand" }
                })
                .AddParagraph(p => p.AddText("Generated by OfficeIMO.Pdf.").SetFontSize(OfficeLength.Points(9)), OfficeAlignment.Right, palette.TextMuted)), new PdfCreateOptions {
                    PageSetup = {
                        Header = { Color = palette.TextMuted, Format = "OfficeIMO.Pdf professional report", Alignment = OfficeAlignment.Left, Offset = global::OfficeIMO.OfficeLength.Points(18), Show = true },
                        Footer = { Alignment = OfficeAlignment.Right, Show = true }
                    },
                    CreateOutlineFromHeadings = true
                })
                .Meta(
                    title: "OfficeIMO.Pdf Professional Report",
                    author: "OfficeIMO",
                    subject: "Dependency-free PDF report example",
                    keywords: "OfficeIMO,Pdf,PSWriteOffice,report")
                .Save(path);

            if (open) {
                System.Diagnostics.Process.Start(new System.Diagnostics.ProcessStartInfo { FileName = path, UseShellExecute = true });
            }
        }

        private static PdfPanelStyle CreateStatusPanelStyle(OfficeThemePalette palette) {
            return new PdfPanelStyle {
                Background = palette.Background,
                BorderColor = palette.Success,
                BorderWidth = OfficeLength.Points(1),
                PaddingX = OfficeLength.Points(10),
                PaddingY = OfficeLength.Points(7)
            };
        }

        private static byte[] CreateFallbackLogo() {
            return OfficePngWriter.EncodeRgba(1, 1, new byte[] { 32, 76, 120, 255 });
        }
    }
}
