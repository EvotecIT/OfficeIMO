"""Generate standard PDF font width, kerning and glyph paint metadata from Adobe's Core 14 AFM files.

The Helvetica and Times core fonts share one 315-glyph set; each AFM glyph name is keyed by its Adobe
Glyph List Unicode value. The oblique Helvetica faces have their upright widths and kerning pairs.
Kerning keeps the AFM KPX pairs whose glyphs are both in that set (Courier has none).
Horizontal and vertical paint bounds cover the twelve supported Helvetica, Times and Courier faces.

Usage (Python 3 with fontTools):
    python Build/Generate-PdfStandardFontWidths.py <directory containing Helvetica.afm, Times-Roman.afm, ...>
"""
import sys
from pathlib import Path

from fontTools import agl

FACES = [
    ("Helvetica", "Helvetica"), ("HelveticaBold", "Helvetica-Bold"),
    ("TimesRoman", "Times-Roman"), ("TimesBold", "Times-Bold"),
    ("TimesItalic", "Times-Italic"), ("TimesBoldItalic", "Times-BoldItalic"),
]
OBLIQUE = [("Helvetica", "Helvetica-Oblique"), ("Helvetica-Bold", "Helvetica-BoldOblique")]
PAINT_FACES = [
    ("Helvetica", "Helvetica"), ("HelveticaOblique", "Helvetica-Oblique"),
    ("HelveticaBold", "Helvetica-Bold"), ("HelveticaBoldOblique", "Helvetica-BoldOblique"),
    ("TimesRoman", "Times-Roman"), ("TimesItalic", "Times-Italic"),
    ("TimesBold", "Times-Bold"), ("TimesBoldItalic", "Times-BoldItalic"),
    ("Courier", "Courier"), ("CourierOblique", "Courier-Oblique"),
    ("CourierBold", "Courier-Bold"), ("CourierBoldOblique", "Courier-BoldOblique"),
]
BACKSLASH = chr(92)
AFM_PERMISSION = (
    "This file and the 14 PostScript(R) AFM files it accompanies may be used, copied, and distributed "
    "for any purpose and without charge, with or without modification, provided that all copyright "
    "notices are retained; that the AFM files are not distributed without this file; that all "
    "modifications to this file or any of the AFM files are prominently noted in the modified file(s); "
    "and that this paragraph is not modified. Adobe Systems has no responsibility or obligation to "
    "support the use of the AFM files."
)


def read_widths(path):
    widths = {}
    for line in path.read_text(encoding="latin-1").splitlines():
        if not line.startswith("C "):
            continue
        fields = [field.strip() for field in line.split(";")]
        width = int(next(field for field in fields if field.startswith("WX "))[3:])
        name = next(field for field in fields if field.startswith("N "))[2:]
        widths[name] = width
    return widths


def read_paint_bounds(path):
    bounds = {}
    notices = set()
    for line in path.read_text(encoding="latin-1").splitlines():
        if line.startswith("Comment Copyright ") or line.startswith("Notice "):
            notices.add(line.split(" ", 1)[1])
        if not line.startswith("C "):
            continue
        fields = [field.strip() for field in line.split(";")]
        name = next(field for field in fields if field.startswith("N "))[2:]
        box = [int(value) for value in next(field for field in fields if field.startswith("B "))[2:].split()]
        assert len(box) == 4 and box[0] <= box[2] and box[1] <= box[3], f"Invalid {name} box in {path}"
        assert all(-32768 <= value <= 32767 for value in box), f"Unrepresentable {name} box in {path}"
        bounds[name] = tuple(box)
    return bounds, notices


def read_kerning(path):
    pairs = {}
    for line in path.read_text(encoding="latin-1").splitlines():
        if not line.startswith("KPX "):
            continue
        _, left, right, value = line.split()
        pairs[(left, right)] = int(value)
    return pairs


def kerning_source(kerning, characters):
    codes = {name: code for code, name in characters.items()}
    out = [
        "namespace OfficeIMO.Pdf;",
        "",
        "// <auto-generated>",
        "// Generated by Build/Generate-PdfStandardFontWidths.py from Adobe's Core 14 AFM files (AFM 4.1).",
        "// AFM KPX pairs keyed by (left << 16 | right) Unicode values; values are in 1/1000 em.",
        "// </auto-generated>",
        "",
        "internal static partial class PdfStandardFontWidths {",
    ]
    for field, afm_name in FACES:
        entries = sorted(
            ((codes[left] << 16) | codes[right], value)
            for (left, right), value in kerning[afm_name].items()
            if left in codes and right in codes and value != 0)
        assert all(-32768 <= value <= 32767 for _, value in entries)
        out += [f"    private static readonly uint[] {field}KerningPairs = {{"]
        out += ["        " + row + "," for row in rows([key for key, _ in entries], 8, lambda value: f"0x{value:08X}")]
        out[-1] = out[-1].rstrip(",")
        out += ["    };", "", f"    private static readonly short[] {field}KerningValues = {{"]
        out += ["        " + row + "," for row in rows([value for _, value in entries], 16, str)]
        out[-1] = out[-1].rstrip(",")
        out += ["    };", ""]
    out += [
        "    /// <summary>Gets the AFM pair kerning between two characters in a Helvetica or Times core font.</summary>",
        "    internal static int GetKerning1000(PdfStandardFont font, char left, char right) {",
        "        (uint[] Pairs, short[] Values)? table = font switch {",
        "            PdfStandardFont.Helvetica or PdfStandardFont.HelveticaOblique => (HelveticaKerningPairs, HelveticaKerningValues),",
        "            PdfStandardFont.HelveticaBold or PdfStandardFont.HelveticaBoldOblique => (HelveticaBoldKerningPairs, HelveticaBoldKerningValues),",
        "            PdfStandardFont.TimesRoman => (TimesRomanKerningPairs, TimesRomanKerningValues),",
        "            PdfStandardFont.TimesBold => (TimesBoldKerningPairs, TimesBoldKerningValues),",
        "            PdfStandardFont.TimesItalic => (TimesItalicKerningPairs, TimesItalicKerningValues),",
        "            PdfStandardFont.TimesBoldItalic => (TimesBoldItalicKerningPairs, TimesBoldItalicKerningValues),",
        "            _ => null",
        "        };",
        "        if (table == null) return 0;",
        "        // WinAnsiEncoding paints the space and hyphen glyphs for these characters.",
        f"        if (left == '{BACKSLASH}u00A0') left = ' ';",
        f"        else if (left == '{BACKSLASH}u00AD') left = '-';",
        f"        if (right == '{BACKSLASH}u00A0') right = ' ';",
        f"        else if (right == '{BACKSLASH}u00AD') right = '-';",
        "        int index = System.Array.BinarySearch(table.Value.Pairs, ((uint)left << 16) | right);",
        "        return index < 0 ? 0 : table.Value.Values[index];",
        "    }",
        "}",
        "",
    ]
    return out


def rows(values, per_line, fmt):
    items = [fmt(value) for value in values]
    return [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]


def paint_bounds_source(faces, characters, order, notices, horizontal=False):
    axis = "HorizontalPaintBounds" if horizontal else "PaintBounds"
    orientation = "Horizontal" if horizontal else "Vertical"
    low, high = ("left", "right") if horizontal else ("bottom", "top")
    first, second = (0, 2) if horizontal else (1, 3)
    out = [
        "namespace OfficeIMO.Pdf;",
        "",
        "// <auto-generated>",
        "// Generated by Build/Generate-PdfStandardFontWidths.py from Adobe's Core 14 AFM files (AFM 4.1).",
        f"// {orientation} glyph bounds extracted from the unchanged source AFMs; keyed by the shared Unicode table.",
        "// </auto-generated>",
        "",
    ]
    out += ["// " + notice for notice in sorted(notices)]
    out += ["// Permission notice from the accompanying MustRead.html:", "// " + AFM_PERMISSION, ""]
    out += [
        f"/// <summary>{orientation} glyph paint bounds of the twelve supported standard faces, in 1/1000 em.</summary>",
        "internal static partial class PdfStandardFontWidths {",
    ]
    for field, afm_name in PAINT_FACES:
        out.append(f"    private static readonly short[] {field}{axis} = {{")
        values = [faces[afm_name][characters[character]][index] for character in order for index in (first, second)]
        out += ["        " + row + "," for row in rows(values, 16, str)]
        out[-1] = out[-1].rstrip(",")
        out += ["    };", ""]
    out += [
        f"    /// <summary>Gets the {low} and {high} glyph bounds using the same Unicode and WinAnsi aliases as advance widths.</summary>",
        f"    internal static bool TryGet{orientation}Bounds1000(PdfStandardFont font, char value, out int {low}, out int {high}) {{",
        "        short[]? bounds = font switch {",
    ]
    out += [f"            PdfStandardFont.{field} => {field}{axis}," for field, _ in PAINT_FACES]
    out += [
        "            _ => null",
        "        };",
        f"        {low} = {high} = 0;",
        "        if (bounds == null) return false;",
        "        // WinAnsiEncoding paints the space and hyphen glyphs for these characters.",
        f"        if (value == '{BACKSLASH}u00A0') value = ' ';",
        f"        else if (value == '{BACKSLASH}u00AD') value = '-';",
        "        int index = GetStandardCharacterIndex(value);",
        "        if (index < 0) return false;",
        f"        {low} = bounds[index * 2];",
        f"        {high} = bounds[index * 2 + 1];",
        "        // A zero box for a non-space glyph (notably Euro) has no qualified ink metadata.",
        f"        return value == ' ' || {low} != 0 || {high} != 0;",
        "    }",
        "}",
        "",
    ]
    return out


def main():
    afm = Path(sys.argv[1])
    faces = {afm_name: read_widths(afm / f"{afm_name}.afm") for _, afm_name in FACES}
    kerning = {afm_name: read_kerning(afm / f"{afm_name}.afm") for _, afm_name in FACES}
    for upright, oblique in OBLIQUE:
        assert read_widths(afm / f"{oblique}.afm") == faces[upright], f"{oblique} widths differ from {upright}"
        assert read_kerning(afm / f"{oblique}.afm") == kerning[upright], f"{oblique} kerning differs from {upright}"
    names = set(faces["Helvetica"])
    assert all(set(widths) == names for widths in faces.values()), "the core fonts have different glyph sets"
    paint_faces = {}
    notices = set()
    for _, afm_name in PAINT_FACES:
        paint_faces[afm_name], face_notices = read_paint_bounds(afm / f"{afm_name}.afm")
        notices.update(face_notices)
    assert all(set(bounds) == names for bounds in paint_faces.values()), "the core paint glyph sets differ"

    characters = {}
    for name in names:
        text = agl.toUnicode(name)
        # commaaccent has only a private-use value; no text decodes to it.
        if len(text) != 1 or 0xE000 <= ord(text) <= 0xF8FF:
            continue
        assert ord(text) not in characters, f"{name} and {characters[ord(text)]} share U+{ord(text):04X}"
        characters[ord(text)] = name
    order = sorted(characters)

    out = [
        "namespace OfficeIMO.Drawing;",
        "",
        "// <auto-generated>",
        "// Generated by Build/Generate-PdfStandardFontWidths.py from Adobe's Core 14 AFM files (AFM 4.1).",
        "// </auto-generated>",
        "",
        *["// " + notice for notice in sorted(notices)],
        "// Permission notice from the accompanying MustRead.html:",
        "// " + AFM_PERMISSION,
        "",
        "/// <summary>Shared standard-font advances in 1/1000 em, keyed by Unicode.</summary>",
        "internal static partial class OfficeStandardFontMetrics {",
        "    private static readonly char[] Characters = {",
    ]
    out += ["        " + row + "," for row in rows(order, 10, lambda value: f"'{BACKSLASH}u{value:04X}'")]
    out[-1] = out[-1].rstrip(",")
    out.append("    };")
    for field, afm_name in FACES:
        out += ["", f"    private static readonly short[] {field} = {{"]
        out += ["        " + row + "," for row in rows([faces[afm_name][characters[value]] for value in order], 16, str)]
        out[-1] = out[-1].rstrip(",")
        out.append("    };")
    out += [
        "",
        "    /// <summary>Gets the width of a character in a Helvetica or Times core font.</summary>",
        "    internal static bool TryGetWidth1000(OfficeStandardFontFace font, char value, out int width) {",
        "        short[]? widths = font switch {",
        "            OfficeStandardFontFace.Helvetica => Helvetica,",
        "            OfficeStandardFontFace.HelveticaBold => HelveticaBold,",
        "            OfficeStandardFontFace.TimesRoman => TimesRoman,",
        "            OfficeStandardFontFace.TimesBold => TimesBold,",
        "            OfficeStandardFontFace.TimesItalic => TimesItalic,",
        "            OfficeStandardFontFace.TimesBoldItalic => TimesBoldItalic,",
        "            _ => null",
        "        };",
        "        width = 0;",
        "        if (widths == null) return false;",
        "        // WinAnsiEncoding paints the space and hyphen glyphs for these characters.",
        f"        if (value == '{BACKSLASH}u00A0') value = ' ';",
        f"        else if (value == '{BACKSLASH}u00AD') value = '-';",
        "        int index = System.Array.BinarySearch(Characters, value);",
        "        if (index < 0) return false;",
        "        width = widths[index];",
        "        return true;",
        "    }",
        "",
        "    internal static int GetCharacterIndex(char value) => System.Array.BinarySearch(Characters, value);",
        "}",
        "",
    ]
    root = Path(__file__).resolve().parents[1]
    core_target = root / "OfficeIMO.Core" / "Fonts" / "OfficeStandardFontMetrics.Data.cs"
    core_target.parent.mkdir(parents=True, exist_ok=True)
    core_target.write_bytes("\r\n".join(out).encode("utf-8"))
    print(f"Wrote {core_target} ({len(order)} characters)")
    target = root / "OfficeIMO.Pdf" / "Rendering" / "Writer" / "PdfStandardFontWidths.cs"
    bridge = [
        "namespace OfficeIMO.Pdf;", "",
        "// <auto-generated>",
        "// Generated by Build/Generate-PdfStandardFontWidths.py. Advance data is owned by OfficeIMO.Core.",
        "// </auto-generated>", "",
        "internal static partial class PdfStandardFontWidths {",
        "    internal static bool TryGetWidth1000(PdfStandardFont font, char value, out int width) {",
        "        OfficeIMO.Drawing.OfficeStandardFontFace? face = font switch {",
    ]
    for field, _ in FACES:
        selector = f"PdfStandardFont.{field}"
        if field in ("Helvetica", "HelveticaBold"):
            selector += f" or PdfStandardFont.{field}Oblique"
        bridge.append(f"            {selector} => OfficeIMO.Drawing.OfficeStandardFontFace.{field},")
    bridge += [
        "            _ => null", "        };", "        width = 0;",
        "        return face.HasValue && OfficeIMO.Drawing.OfficeStandardFontMetrics.TryGetWidth1000(face.Value, value, out width);",
        "    }", "",
        "    private static int GetStandardCharacterIndex(char value) => OfficeIMO.Drawing.OfficeStandardFontMetrics.GetCharacterIndex(value);",
        "}", "",
    ]
    target.write_bytes("\r\n".join(bridge).encode("utf-8"))
    print(f"Wrote {target} (shared advance adapter)")
    paint_target = target.with_name("PdfStandardFontWidths.PaintBounds.cs")
    paint_target.write_bytes("\r\n".join(paint_bounds_source(paint_faces, characters, order, notices)).encode("utf-8"))
    print(f"Wrote {paint_target} ({len(PAINT_FACES)} faces, {len(order)} characters)")
    horizontal_target = target.with_name("PdfStandardFontWidths.HorizontalPaintBounds.cs")
    horizontal_target.write_bytes("\r\n".join(paint_bounds_source(paint_faces, characters, order, notices, horizontal=True)).encode("utf-8"))
    print(f"Wrote {horizontal_target} ({len(PAINT_FACES)} faces, {len(order)} characters)")
    kerning_target = target.with_name("PdfStandardFontWidths.Kerning.cs")
    kerning_target.write_bytes("\r\n".join(kerning_source(kerning, characters)).encode("utf-8"))
    print(f"Wrote {kerning_target} ({len(FACES)} faces)")


if __name__ == "__main__":
    main()
