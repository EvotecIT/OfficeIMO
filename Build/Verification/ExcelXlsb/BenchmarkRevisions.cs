using BenchmarkDotNet.Attributes;
using BenchmarkDotNet.Running;
using OfficeIMO.Excel;

if (args.Length == 2 && args[0] == "seed") {
    File.WriteAllBytes(args[1], XlsbMigrationBenchmarks.CreateNativeWorkbook());
} else {
    BenchmarkSwitcher.FromAssembly(typeof(XlsbMigrationBenchmarks).Assembly).Run(args);
}

[MemoryDiagnoser]
public class XlsbMigrationBenchmarks {
    private const int Rows = 1_000;
    private const int Columns = 10;
    private static readonly ExcelSaveOptions Native = new() { Format = ExcelFileFormat.Xlsb };
    private byte[] _input = null!;

    [GlobalSetup]
    public void Setup() {
        string inputFile = Environment.GetEnvironmentVariable("OFFICEIMO_XLSB_BENCH_INPUT")
            ?? throw new InvalidOperationException("Set OFFICEIMO_XLSB_BENCH_INPUT to a workbook generated by the seed command.");
        _input = File.ReadAllBytes(inputFile);
        ValidateWorkbook(_input, Rows * Columns);
        ValidateWorkbook(CreateNativeWorkbook(), Rows * Columns);
        ValidateWorkbook(EditWorkbook(), -42);
    }

    [Benchmark]
    public int Import() {
        using ExcelDocument document = Load(_input);
        return document.Sheets.Count;
    }

    [Benchmark]
    public byte[] CreateAndSave() => CreateNativeWorkbook();

    [Benchmark]
    public int ImportEditAndSave() => EditWorkbook().Length;

    internal static byte[] CreateNativeWorkbook() {
        using ExcelDocument document = ExcelDocument.Create();
        ExcelSheet sheet = document.AddSheet("Data");
        int value = 0;
        for (int row = 1; row <= Rows; row++) {
            for (int column = 1; column <= Columns; column++) {
                sheet.Cell(row, column).SetValue(++value);
            }
        }
        return document.ToBytes(Native);
    }

    private byte[] EditWorkbook() {
        using ExcelDocument document = Load(_input);
        document.Sheets[0].Cell(Rows, Columns).SetValue(-42);
        return document.ToBytes(Native);
    }

    private static void ValidateWorkbook(byte[] bytes, int expectedLastValue) {
        using ExcelDocument document = Load(bytes);
        if (document.Sheets.Count != 1 || document.Sheets[0].Cell(Rows, Columns).GetValue<int>() != expectedLastValue)
            throw new InvalidDataException("The benchmark did not produce the expected workbook.");
    }

    private static ExcelDocument Load(byte[] bytes) {
        using var stream = new MemoryStream(bytes, writable: false);
        return ExcelDocument.Load(stream);
    }
}
