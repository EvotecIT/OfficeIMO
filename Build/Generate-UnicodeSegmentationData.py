"""Generate the UAX #29 word and grapheme cluster segmentation tables from the Unicode Character Database.

The output backs OfficeIMO.TextAnalysis.UnicodeTextSegmenter (public in OfficeIMO.Core, linked as internal source into
OfficeIMO.Reader.Core). Each code point gets one packed 16-bit value:

    bits 0-4   Word_Break
    bits 5-8   Grapheme_Cluster_Break
    bits 9-10  Indic_Conjunct_Break (None, Linker, Consonant, Extend)
    bit  11    Extended_Pictographic

Values are stored as sorted range starts with one value per range, plus a direct table for code points below 0x100,
so a lookup is an array read for Latin-1 and a binary search otherwise.

Usage (Python 3, no third-party packages):
    python Build/Generate-UnicodeSegmentationData.py <directory containing the UCD 16.0.0 files>

Required files (relative to the directory, with or without their UCD subfolder):
    auxiliary/WordBreakProperty.txt, auxiliary/GraphemeBreakProperty.txt, DerivedCoreProperties.txt and
    emoji/emoji-data.txt. Download them from https://www.unicode.org/Public/16.0.0/ucd/.

The conformance files auxiliary/WordBreakTest.txt and auxiliary/GraphemeBreakTest.txt are vendored separately under
OfficeIMO.Drawing.Tests/TestAssets/Unicode and are not read by this script.
"""
import hashlib
import re
import sys
from pathlib import Path

UNICODE_VERSION = "16.0.0"
WORD_BREAK = ["Other", "CR", "LF", "Newline", "Extend", "ZWJ", "Regional_Indicator", "Format", "Katakana",
              "Hebrew_Letter", "ALetter", "Single_Quote", "Double_Quote", "MidNumLet", "MidLetter", "MidNum",
              "Numeric", "ExtendNumLet", "WSegSpace"]
GRAPHEME_BREAK = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend", "SpacingMark",
                  "L", "V", "T", "LV", "LVT"]
INCB = ["None", "Linker", "Consonant", "Extend"]
DATA_LINE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([^#;]+?)\s*(?:;\s*([^#\s;]+))?\s*(?:#|$)")


def find(root, *names):
    for name in names:
        path = root / name
        if path.exists():
            return path
    raise FileNotFoundError(f"None of {names} found in {root}")


def assign(path, values, select):
    """Applies select(property, value) -> int|None to every data line."""
    for line in path.read_text(encoding="utf-8").splitlines():
        match = DATA_LINE.match(line)
        if not match:
            continue
        start = int(match.group(1), 16)
        end = int(match.group(2), 16) if match.group(2) else start
        result = select(match.group(3).strip(), match.group(4))
        if result is None:
            continue
        for code in range(start, end + 1):
            values[code] = result


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    root = Path(sys.argv[1])
    files = {
        "auxiliary/WordBreakProperty.txt": find(root, "auxiliary/WordBreakProperty.txt", "WordBreakProperty.txt"),
        "auxiliary/GraphemeBreakProperty.txt": find(root, "auxiliary/GraphemeBreakProperty.txt",
                                                    "GraphemeBreakProperty.txt"),
        "DerivedCoreProperties.txt": find(root, "DerivedCoreProperties.txt"),
        "emoji/emoji-data.txt": find(root, "emoji/emoji-data.txt", "emoji-data.txt"),
    }
    for name, path in files.items():
        header = "\n".join(path.read_text(encoding="utf-8").splitlines()[:12])
        if UNICODE_VERSION not in header and f"Emoji Version {UNICODE_VERSION[:-2]}" not in header:
            raise ValueError(f"{name} is not from Unicode {UNICODE_VERSION}")

    word = [0] * 0x110000
    grapheme = [0] * 0x110000
    incb = [0] * 0x110000
    pictographic = [0] * 0x110000
    assign(files["auxiliary/WordBreakProperty.txt"], word,
           lambda prop, _: WORD_BREAK.index(prop))
    assign(files["auxiliary/GraphemeBreakProperty.txt"], grapheme,
           lambda prop, _: GRAPHEME_BREAK.index(prop))
    assign(files["DerivedCoreProperties.txt"], incb,
           lambda prop, value: INCB.index(value) if prop == "InCB" else None)
    assign(files["emoji/emoji-data.txt"], pictographic,
           lambda prop, _: 1 if prop == "Extended_Pictographic" else None)

    packed = [word[c] | (grapheme[c] << 5) | (incb[c] << 9) | (pictographic[c] << 11) for c in range(0x110000)]
    starts, values = [], []
    for code, value in enumerate(packed):
        if not values or values[-1] != value:
            starts.append(code)
            values.append(value)

    def array(name, kind, items, per_line):
        out = [f"    private static readonly {kind}[] {name} = {{"]
        for index in range(0, len(items), per_line):
            out.append("        " + ", ".join(items[index:index + per_line]) + ",")
        out[-1] = out[-1].rstrip(",")
        out.append("    };")
        return out

    out = ["// <auto-generated>",
           f"// Generated by Build/Generate-UnicodeSegmentationData.py from UCD {UNICODE_VERSION}."]
    for name, path in files.items():
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        out.append(f"// https://www.unicode.org/Public/{UNICODE_VERSION}/ucd/{name}")
        out.append(f"// SHA256 {digest}")
    out += ["// Unicode data files are licensed under Unicode License v3 (https://www.unicode.org/license.txt).",
            "// </auto-generated>",
            "",
            "#if OFFICEIMO_READER_CORE",
            "namespace OfficeIMO.Reader.Internal.TextAnalysis;",
            "#else",
            "namespace OfficeIMO.TextAnalysis;",
            "#endif",
            "",
            "internal static partial class UnicodeSegmentationData {",
            f"    /// <summary>Unicode version the tables were generated from.</summary>",
            f"    internal const string UnicodeVersion = \"{UNICODE_VERSION}\";",
            ""]
    out += array("Latin1Values", "ushort", [str(value) for value in packed[:0x100]], 24)
    out += [""]
    out += array("RangeStarts", "int", [f"0x{value:X}" for value in starts], 10)
    out += [""]
    out += array("RangeValues", "ushort", [str(value) for value in values], 20)
    out += ["}", ""]

    target = (Path(__file__).resolve().parents[1] / "OfficeIMO.SharedSource" / "TextAnalysis" /
              "UnicodeSegmentationData.Generated.cs")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes("\n".join(out).encode("utf-8"))
    print(f"Wrote {target} ({len(starts)} ranges).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
