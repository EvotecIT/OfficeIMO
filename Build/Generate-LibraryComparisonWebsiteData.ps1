#requires -Version 7.4
<#
.SYNOPSIS
Generates website benchmark data and comparison partials from a v4 catalog.
.DESCRIPTION
The catalog is the only evidence input. This does not measure workloads, promote
quick results, fill missing environments, or update the legacy Excel matrix.
.PARAMETER CatalogPath
Merged PowerForge v4 index.json to validate and render.
.PARAMETER OutputDirectory
Directory receiving benchmarks-catalog.html and benchmarks-overview.html.
.PARAMETER WebsiteIndexPath
Build-time template data file receiving the exact published catalog bytes.
.PARAMETER DryRun
Validates the catalog and returns output paths without writing files.
.EXAMPLE
./Build/Generate-LibraryComparisonWebsiteData.ps1 -CatalogPath ./Website/static/data/benchmarks/library-comparisons/index.json
.OUTPUTS
An output plan in DryRun mode. Otherwise writes two UTF-8 HTML partials and an
identical catalog copy.
#>
[CmdletBinding()]
param(
    [string] $CatalogPath = (Join-Path $PSScriptRoot '../Website/static/data/benchmarks/library-comparisons/index.json'),
    [string] $OutputDirectory = (Join-Path $PSScriptRoot '../Website/themes/officeimo/partials/generated'),
    [string] $WebsiteIndexPath = (Join-Path $PSScriptRoot '../Website/data/benchmarks_index.json'),
    [switch] $DryRun
)

$ErrorActionPreference = 'Stop'
$CatalogPath = (Resolve-Path -LiteralPath $CatalogPath -ErrorAction Stop).ProviderPath
$OutputDirectory = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($OutputDirectory)
$WebsiteIndexPath = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($WebsiteIndexPath)
$catalogBytes = [System.IO.File]::ReadAllBytes($CatalogPath)
$json = [System.Text.Encoding]::UTF8.GetString($catalogBytes).TrimStart([char] 0xFEFF)
if (-not (Test-Json -Json $json -SchemaFile (Join-Path $PSScriptRoot 'library-comparisons.schema.json'))) {
    throw "Invalid v4 comparison catalog: '$CatalogPath'."
}
$catalog = $json | ConvertFrom-Json -Depth 100
$outputPaths = @('benchmarks-catalog.html', 'benchmarks-overview.html') | ForEach-Object { Join-Path $OutputDirectory $_ }
$outputPaths += $WebsiteIndexPath
if ($DryRun) {
    [pscustomobject]@{
        DryRun = $true
        CatalogPath = $CatalogPath
        OutputPath = @($outputPaths)
        ComparisonCount = @($catalog.comparisons).Count
        EntryCount = @($catalog.entries).Count
    }
    return
}

function ConvertTo-HtmlText([object] $Value) {
    [System.Net.WebUtility]::HtmlEncode([string] $Value).Replace('{', '&#123;').Replace('}', '&#125;')
}

# Only portable local evidence links are rendered; catalog strings never become
# executable URLs, markup, or template expressions.
function Get-EvidenceLink([object] $Entry) {
    $path = [string] $Entry.resultPath
    if ($path -notmatch '^/data/benchmarks/[^\\<>"{}\s]+\.json$' -or
        $path.Contains('..') -or $path.Contains('?') -or $path.Contains('#')) {
        return 'Result path unavailable'
    }
    '<a href="' + (ConvertTo-HtmlText $path) + '">Inspect result</a>'
}

function Get-PlatformEvidence([string] $ComparisonId, [string] $Platform) {
    $entries = @($catalog.entries | Where-Object { $_.comparisonId -eq $ComparisonId -and $_.platform -eq $Platform })
    $published = @($entries | Where-Object { $_.publish -and $_.runMode -eq 'full' })
    $latest = $entries | Sort-Object { [DateTimeOffset]::Parse($_.generatedUtc) } -Descending | Select-Object -First 1
    $status = if ($published.Count -gt 0) {
        $latest = $published | Sort-Object { [DateTimeOffset]::Parse($_.generatedUtc) } -Descending | Select-Object -First 1
        if ($latest.comparable) { 'Full evidence' } else { 'Full evidence; incompatible lanes' }
    } elseif ($entries.Count -gt 0) {
        'Diagnostic evidence only'
    } else {
        'Not run yet'
    }
    if ($null -eq $latest) {
        return $status
    }
    $date = ([DateTimeOffset]::Parse($latest.generatedUtc)).ToUniversalTime().ToString('yyyy-MM-dd')
    $environment = @($latest.environment.processorName, $latest.environment.osDescription, $latest.environment.runtimeVersion) |
        Where-Object { -not [string]::IsNullOrWhiteSpace($_) }
    $environmentLabel = if (@($environment).Count -gt 0) { $environment -join '; ' } else { 'Environment not recorded' }
    (ConvertTo-HtmlText $status) + '<br><time datetime="' + (ConvertTo-HtmlText $latest.generatedUtc) + '">' + $date +
        '</time><br>' + (ConvertTo-HtmlText $environmentLabel) + '<br>' + (Get-EvidenceLink $latest)
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('<!-- Generated by Build/Generate-LibraryComparisonWebsiteData.ps1. -->')
$lines.Add('<section class="imo-benchmark-evidence" aria-labelledby="benchmark-catalog-title">')
$lines.Add('<div class="imo-benchmark-evidence__intro"><h2 id="benchmark-catalog-title">Library comparison catalog</h2><p>Coverage comes from declared workloads and recorded evidence. Compare results within the same workload, environment and measurement profile.</p></div>')
foreach ($area in @($catalog.areas | Sort-Object)) {
    $lines.Add('<section class="imo-benchmark-family imo-benchmark-highlight" id="benchmark-area-' + (ConvertTo-HtmlText $area) + '">')
    $lines.Add('<header class="imo-benchmark-family__header"><h3>' + (ConvertTo-HtmlText $area) + '</h3></header>')
    $lines.Add('<div class="imo-benchmark-highlight__table-wrap" role="region" aria-label="' + (ConvertTo-HtmlText $area) + ' comparison evidence" tabindex="0"><table><thead><tr><th scope="col">Comparison</th><th scope="col">Libraries</th>')
    foreach ($platform in $catalog.expectedPlatforms) {
        $lines.Add('<th scope="col">' + (ConvertTo-HtmlText $platform) + '</th>')
    }
    $lines.Add('</tr></thead><tbody>')
    foreach ($comparison in @($catalog.comparisons | Where-Object area -eq $area | Sort-Object comparisonId)) {
        $lines.Add('<tr><th scope="row">' + (ConvertTo-HtmlText $comparison.title) + '<br><small>' + (ConvertTo-HtmlText $comparison.comparisonId) + '</small></th><td>' + (ConvertTo-HtmlText ($comparison.libraries -join ', ')) + '</td>')
        foreach ($platform in $catalog.expectedPlatforms) {
            $status = if ($platform -notin $comparison.expectedPlatforms) { 'Not targeted' } else { Get-PlatformEvidence $comparison.comparisonId $platform }
            $lines.Add('<td>' + $status + '</td>')
        }
        $lines.Add('</tr>')
    }
    $lines.Add('</tbody></table></div></section>')
}
$lines.Add('</section>')

$overview = [System.Collections.Generic.List[string]]::new()
$overview.Add('<!-- Generated by Build/Generate-LibraryComparisonWebsiteData.ps1. -->')
$overview.Add('<section class="imo-benchmark-evidence imo-benchmark-highlight" aria-labelledby="benchmark-evidence-title">')
$overview.Add('<div class="imo-benchmark-evidence__intro"><h2 id="benchmark-evidence-title">Recorded comparison coverage</h2><p>Full evidence and diagnostic runs are shown separately. Missing runs do not imply a performance result. Different machines and source revisions remain separate evidence lanes.</p></div>')
$overview.Add('<div class="imo-benchmark-highlight__table-wrap"><table><thead><tr><th scope="col">Area</th><th scope="col">Declared comparisons</th><th scope="col">Full evidence lanes</th><th scope="col">Diagnostic lanes</th></tr></thead><tbody>')
foreach ($area in @($catalog.areas | Sort-Object)) {
    $comparisons = @($catalog.comparisons | Where-Object area -eq $area)
    $entries = @($catalog.entries | Where-Object area -eq $area)
    $full = @($entries | Where-Object { $_.publish -and $_.runMode -eq 'full' })
    $diagnostic = $entries.Count - $full.Count
    $overview.Add('<tr><th scope="row">' + (ConvertTo-HtmlText $area) + '</th><td>' + $comparisons.Count + '</td><td>' + $full.Count + '</td><td>' + $diagnostic + '</td></tr>')
}
$overview.Add('</tbody></table></div><p><a href="/data/benchmarks/library-comparisons/index.json">Inspect the evidence catalog</a></p></section>')

New-Item -ItemType Directory -Path $OutputDirectory -Force | Out-Null
[System.IO.File]::WriteAllText($outputPaths[0], ($lines -join "`n") + "`n", [System.Text.UTF8Encoding]::new($false))
[System.IO.File]::WriteAllText($outputPaths[1], ($overview -join "`n") + "`n", [System.Text.UTF8Encoding]::new($false))
New-Item -ItemType Directory -Path (Split-Path -Parent $WebsiteIndexPath) -Force | Out-Null
[System.IO.File]::WriteAllBytes($WebsiteIndexPath, $catalogBytes)
Write-Host "Generated comparison partials in '$OutputDirectory' and catalog data at '$WebsiteIndexPath'."
