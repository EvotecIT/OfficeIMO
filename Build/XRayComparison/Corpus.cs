using System.Text;
using OfficeIMO.Excel;
using OfficeIMO.Word;

namespace OfficeIMO.XRayComparison;

/// <summary>One input file for one workload.</summary>
internal sealed record BenchCase(string Id, string Format, string Size, string Path, string Origin) {
    public long Bytes => new FileInfo(Path).Length;
    public string FileName => System.IO.Path.GetFileName(Path);
    public override string ToString() => Id;
}

/// <summary>
/// Repository fixtures plus a few deterministic generated inputs for sizes the repository does not hold
/// (a text-heavy large DOCX and a large XLSX with currency, percent and date formats).
/// </summary>
internal static class Corpus {
    private static readonly object Gate = new();
    private static bool _generated;

    public static string RepoRoot { get; } = FindRepoRoot();

    public static string WorkRoot { get; } = Environment.GetEnvironmentVariable("XRAY_BENCH_WORK") is { Length: > 0 } work
        ? System.IO.Path.GetFullPath(work)
        : System.IO.Path.Combine(System.IO.Path.GetTempPath(), "officeimo-xray-bench");

    public static string FixtureRoot => System.IO.Path.Combine(WorkRoot, "fixtures");

    private static string Repo(string relative) => System.IO.Path.Combine(RepoRoot, relative.Replace('/', System.IO.Path.DirectorySeparatorChar));
    private static string Generated(string name) => System.IO.Path.Combine(FixtureRoot, name);

    public static IReadOnlyList<BenchCase> Extraction => Ensure([
        new("docx-s", "docx", "S", Repo("OfficeIMO.Pdf.Tests/Pdf/ReferenceBaselines/native-word-report.docx"), "repo, Word-authored"),
        new("docx-m", "docx", "M", Repo("OfficeIMO.TestAssets/Documents/sample2.docx"), "repo"),
        new("docx-l", "docx", "L", Generated("word-large.docx"), "generated by OfficeIMO.Word"),
        new("xlsx-s", "xlsx", "S", Repo("OfficeIMO.Pdf.Tests/Pdf/ReferenceBaselines/native-excel-daily-workbook.xlsx"), "repo, Excel-authored"),
        new("xlsx-m", "xlsx", "M", Repo("OfficeIMO.TestAssets/Documents/SampleFileExcel.xlsx"), "repo"),
        new("xlsx-l", "xlsx", "L", Generated("excel-large.xlsx"), "generated by OfficeIMO.Excel"),
        new("pptx-s", "pptx", "S", Repo("OfficeIMO.Pdf.Tests/Pdf/ReferenceBaselines/native-powerpoint-dense-layout.pptx"), "repo, PowerPoint-authored"),
        new("pptx-m", "pptx", "M", Repo("Assets/PowerPointTemplates/PowerPointWithTablesAndCharts.pptx"), "repo"),
        new("pptx-l", "pptx", "L", Repo("OfficeIMO.TestAssets/Documents/IWorkCorpus/native-exports/keynote-scale-512-v15.4.pptx"), "repo, Keynote export"),
        new("pdf-s", "pdf", "S", Repo("OfficeIMO.TestAssets/Documents/IWorkCorpus/native-exports/pages-table-borders-v15.4.pdf"), "repo, Pages export"),
        new("pdf-m", "pdf", "M", Repo("OfficeIMO.TestAssets/Pdf/IndependentCorpus/acl-2021-mt5-multilingual.pdf"), "repo, independent corpus"),
        new("pdf-l", "pdf", "L", Repo("OfficeIMO.TestAssets/Pdf/IndependentCorpus/nist-sp800-63-3.pdf"), "repo, independent corpus"),
    ]);

    public static IReadOnlyList<BenchCase> OfficeToPdf => Ensure(Extraction.Where(item => item.Format is "docx" or "xlsx" or "pptx").ToArray());

    public static BenchCase Get(string id) =>
        Extraction.First(item => string.Equals(item.Id, id, StringComparison.OrdinalIgnoreCase));

    public static string MimeType(BenchCase item) => item.Format switch {
        "docx" => "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        "xlsx" => "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        "pptx" => "application/vnd.openxmlformats-officedocument.presentationml.presentation",
        "pdf" => "application/pdf",
        _ => "application/octet-stream"
    };

    private static IReadOnlyList<BenchCase> Ensure(IReadOnlyList<BenchCase> cases) {
        EnsureGenerated();
        foreach (BenchCase item in cases) {
            if (!File.Exists(item.Path)) throw new FileNotFoundException($"Fixture {item.Id} is missing.", item.Path);
        }
        return cases;
    }

    public static void EnsureGenerated() {
        lock (Gate) {
            if (_generated) return;
            Directory.CreateDirectory(FixtureRoot);
            GenerateIfMissing("word-large.docx", BuildWord);
            GenerateIfMissing("excel-large.xlsx", BuildExcel);
            _generated = true;
        }
    }

    private static void GenerateIfMissing(string name, Action<string> build) {
        string path = Generated(name);
        if (File.Exists(path)) return;
        string temporary = path + ".partial" + System.IO.Path.GetExtension(path);
        if (File.Exists(temporary)) File.Delete(temporary);
        build(temporary);
        File.Move(temporary, path, overwrite: true);
    }

    // Deterministic vocabulary so word recall is meaningful (no repeated single sentence).
    private static readonly string[] Vocabulary = (
        "invoice ledger quarterly revenue forecast margin regional supplier contract renewal audit " +
        "compliance retention schedule warehouse shipment backlog variance budget capital expense " +
        "headcount payroll pension insurance premium claim settlement liability exposure hedge " +
        "currency exchange treasury liquidity covenant lender maturity coupon dividend equity " +
        "subsidiary acquisition integration synergy roadmap milestone deliverable stakeholder " +
        "governance escalation incident outage latency throughput capacity migration rollout " +
        "żółw gęś łąka Zürich Ångström naïve façade coöperate résumé crème").Split(' ');

    private static string Words(Random random, int count) {
        var builder = new StringBuilder();
        for (int index = 0; index < count; index++) {
            if (index > 0) builder.Append(' ');
            builder.Append(Vocabulary[random.Next(Vocabulary.Length)]);
            if (random.Next(9) == 0) builder.Append(' ').Append(random.Next(1, 100_000));
        }
        return builder.Append('.').ToString();
    }

    private static void BuildWord(string path) {
        var random = new Random(20261117);
        using (WordDocument document = WordDocument.Create(path)) {
            for (int section = 1; section <= 240; section++) {
                document.AddParagraph($"Section {section} {Vocabulary[section % Vocabulary.Length]}").Style = WordParagraphStyles.Heading1;
                for (int paragraph = 0; paragraph < 5; paragraph++) document.AddParagraph(Words(random, 40 + random.Next(40)));
                if (section % 8 == 0) {
                    WordTable table = document.AddTable(10, 5);
                    for (int row = 0; row < 10; row++) {
                        for (int column = 0; column < 5; column++) {
                            table.Rows[row].Cells[column].Paragraphs[0].Text = row == 0
                                ? $"Column {column + 1}"
                                : $"{Vocabulary[random.Next(Vocabulary.Length)]} {random.Next(1, 10_000)}";
                        }
                    }
                }
            }
            document.Save();
        }
    }

    private static void BuildExcel(string path) {
        var random = new Random(4242);
        string[] regions = ["North", "South", "East", "West", "Central"];
        using (ExcelDocument document = ExcelDocument.Create(path)) {
            ExcelSheet sheet = document.AddSheet("Sales");
            string[] headers = ["Id", "Region", "Product", "Units", "Price", "Discount", "Shipped", "Note"];
            for (int column = 0; column < headers.Length; column++) sheet.Cell(1, column + 1).SetValue(headers[column]);
            const int rows = 10_000;
            for (int row = 2; row <= rows + 1; row++) {
                sheet.Cell(row, 1).SetValue(row - 1);
                sheet.Cell(row, 2).SetValue(regions[random.Next(regions.Length)]);
                sheet.Cell(row, 3).SetValue("Product " + Vocabulary[random.Next(Vocabulary.Length)]);
                sheet.Cell(row, 4).SetValue(random.Next(1, 500));
                sheet.Cell(row, 5).SetValue(Math.Round((decimal)(random.NextDouble() * 5000), 2));
                sheet.Cell(row, 6).SetValue(Math.Round(random.NextDouble() * 0.3, 3));
                sheet.Cell(row, 7).SetValue(new DateTime(2026, 1, 1).AddDays(random.Next(365)));
                sheet.Cell(row, 8).SetValue(Words(random, 4));
            }
            sheet.Cell(2, 5).SetValue(31200m);
            sheet.Cell(2, 6).SetValue(0.032);
            sheet.Range(2, 5, rows + 1, 5).SetNumberFormat("$#,##0.00");
            sheet.Range(2, 6, rows + 1, 6).SetNumberFormat("0.0%");
            sheet.Range(2, 7, rows + 1, 7).SetNumberFormat("yyyy-mm-dd");
            document.Save();
        }
    }

    private static string FindRepoRoot() {
        string? configured = Environment.GetEnvironmentVariable("XRAY_BENCH_REPO");
        if (!string.IsNullOrWhiteSpace(configured)) return System.IO.Path.GetFullPath(configured);
        foreach (string start in new[] { AppContext.BaseDirectory, Environment.CurrentDirectory }) {
            var directory = new DirectoryInfo(start);
            while (directory != null) {
                if (File.Exists(System.IO.Path.Combine(directory.FullName, "OfficeIMO.slnx"))) return directory.FullName;
                directory = directory.Parent;
            }
        }
        throw new InvalidOperationException("Cannot find the OfficeIMO repository root. Set XRAY_BENCH_REPO.");
    }
}
