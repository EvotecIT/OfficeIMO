namespace OfficeIMO.Visio {
    /// <summary>Native Visio display-time capitalization modes.</summary>
    public enum VisioTextCapitalization {
        /// <summary>Preserves the stored text casing.</summary>
        Normal = 0,
        /// <summary>Displays lowercase letters as capitals.</summary>
        AllCaps = 1,
        /// <summary>Displays the first letter of each word as a capital.</summary>
        InitialCaps = 2
    }
}
