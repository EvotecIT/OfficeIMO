// Deterministic assembly of tsc's local, acyclic ESM graph. No npm bundler or minifier.
// Supported syntax: named imports/exports, declarations, namespace re-exports.
// Reject other module syntax rather than silently assembling a broken portable script.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve, dirname, relative, join } from "node:path";
import { createHash } from "node:crypto";

const root = fileURLToPath(new URL("../", import.meta.url)), dist = join(root, "dist");
const check = process.argv.includes("--check"), output = join(root, "bundles");
const banner = "// Generated by OfficeIMO.JavaScript/scripts/bundles.mjs from tsc output. MIT.\n";
await mkdir(output, { recursive: true });

function bindings(text) {
  return text.split(",").map(s => s.trim()).filter(Boolean).map(s => {
    const match = /^(\w+)(?:\s+as\s+(\w+))?$/.exec(s);
    if (!match) throw new Error("Unsupported module binding: " + s);
    return { source: match[1], name: match[2] ?? match[1] };
  });
}

for (const [name, entry, namespaces] of [
  ["officeimo", "index.js", []],
  ["officeimo-xlsx", "xlsx/index.js", ["core", "zip", "xml", "opc", "xlsx"]],
  ["officeimo-csv", "csv/index.js", ["core", "csv"]]
]) {
  const modules = new Map(), ordered = [], visiting = new Set();
  async function visit(path) {
    if (visiting.has(path)) throw new Error("Classic graph must be acyclic: " + relative(dist, path));
    if (modules.has(path)) return modules.get(path);
    if (!path.startsWith(dist + "/") && !path.startsWith(dist + "\\")) throw new Error("Module escaped dist.");
    const module = { id: "_m" + modules.size, exports: new Map(), source: "", key: "" };
    modules.set(path, module); visiting.add(path);
    let source = (await readFile(path, "utf8")).replace(/\r\n/g, "\n");
    const identity = createHash("sha256").update(relative(dist, path).replace(/\\/g, "/") + "\n" + source);
    const references = [...source.matchAll(/^(import|export)\s+(\{[^}]*\}|\* as \w+)\s+from\s+"([^"]+)";\s*$/gm)];
    for (const match of references) {
      const [, kind, clause, specifier] = match;
      if (!specifier.startsWith(".")) throw new Error("Runtime dependency is forbidden: " + specifier);
      const dependency = await visit(resolve(dirname(path), specifier));
      identity.update("\n" + dependency.key);
      let replacement = "";
      if (clause.startsWith("* as ")) {
        if (kind !== "export") throw new Error("Unsupported namespace import.");
        module.exports.set(clause.slice(5), dependency.id);
      } else {
        const list = bindings(clause.slice(1, -1));
        for (const binding of list) if (!dependency.exports.has(binding.source)) throw new Error("Unknown export " + binding.source + " from " + specifier);
        if (kind === "import") replacement = "const { " + list.map(b => b.source === b.name ? b.name : b.source + ": " + b.name).join(", ") + " } = " + dependency.id + ";";
        else for (const binding of list) module.exports.set(binding.name, dependency.id + "." + binding.source);
      }
      source = source.replace(match[0], replacement + "\n");
    }
    source = source.replace(/^export\s+((?:async\s+)?function\*?|class|const|let)\s+(\w+)/gm, (_, declaration, symbol) => {
      module.exports.set(symbol, symbol); return declaration + " " + symbol;
    }).replace(/^export\s*\{([^}]*)\};\s*$/gm, (_, list) => {
      for (const b of bindings(list)) module.exports.set(b.name, b.source);
      return "";
    });
    if (/^\s*(?:import|export)\b/m.test(source)) throw new Error("Unsupported module syntax in " + relative(dist, path));
    module.source = source.trimEnd(); module.key = identity.digest("hex");
    visiting.delete(path); ordered.push(module); return module;
  }
  const main = await visit(join(dist, entry));
  const namespaceModules = [];
  for (const ns of namespaces) namespaceModules.push([ns, await visit(join(dist, ns, "index.js"))]);
  function graph(cached) {
    return ordered.map(m => "const " + m.id + " = " + (cached ? '_modules.get("' + m.key + '") ?? ' : "") +
      "(() => {\n" + m.source + "\nconst _exports = Object.freeze({ " +
      [...m.exports].map(([key, value]) => key + ": " + value).join(", ") + " });\n" +
      (cached ? '_modules.set("' + m.key + '", _exports);\n' : "") + "return _exports;\n})();").join("\n\n");
  }
  const fields = [...main.exports.keys()];
  // Standalone scripts reuse identical modules, including error/model class identities.
  // Hashing source and dependency identities prevents mixing different module versions.
  const classic = banner + '(function (root) {\n"use strict";\nconst officeimo = root.OfficeIMO || (root.OfficeIMO = {});\n' +
    'const cacheKey = Symbol.for("@evotecit/officeimo/modules");\n' +
    'const _modules = officeimo[cacheKey] || new Map();\n' +
    'if (!officeimo[cacheKey]) Object.defineProperty(officeimo, cacheKey, { value: _modules });\n' + graph(true) + "\nObject.assign(officeimo, " + main.id +
    (namespaceModules.length ? ", { " + namespaceModules.map(([key, m]) => key + ": " + m.id).join(", ") + " }" : "") + ");\n})(globalThis);\n";
  const esm = banner + graph(false) + "\nconst { " + fields.join(", ") + " } = " + main.id + ";\nexport { " + fields.join(", ") + " };\n";
  for (const [file, content] of [[name + ".js", classic], [name + ".mjs", esm]]) {
    const path = join(output, file);
    if (check) {
      let actual;
      try { actual = await readFile(path, "utf8"); } catch { /* missing is stale too */ }
      if (actual !== content) throw new Error("Stale bundle " + file + "; run npm run build and commit it.");
    } else await writeFile(path, content, "utf8");
  }
}
