// Deterministic assembly of tsc's local, acyclic ESM graph. No npm bundler or minifier.
// Supported syntax: named imports/exports, declarations, namespace re-exports.
// Reject other module syntax rather than silently assembling a broken portable script.
//
// Every bundle has a readable variant (from dist) and a compact .min variant (from the comment-free dist-min emit,
// with insignificant whitespace removed). Module identities hash the readable source, so readable and compact
// scripts of one build share modules and class identities on the same page.
//
// The DataTables and CanopyX integrations also ship as thin adapters: officeimo-<name>-adapter.{js,mjs} carry only
// the integration modules and take the shared writer modules from officeimo.{js,mjs} of the same build.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve, dirname, relative, join } from "node:path";
import { createHash } from "node:crypto";

const root = fileURLToPath(new URL("../", import.meta.url)), dist = join(root, "dist"), distMin = join(root, "dist-min");
const check = process.argv.includes("--check"), output = join(root, "bundles");
const banner = "// Generated by OfficeIMO.JavaScript/scripts/bundles.mjs from tsc output. MIT.\n";
const cacheSymbol = "@evotecit/officeimo/modules", registryName = "__officeimoModules", core = "officeimo";
await mkdir(output, { recursive: true });

const bundles = [
  ["officeimo", "index.js", []],
  ["officeimo-xlsx", "xlsx/index.js", ["core", "zip", "xml", "opc", "xlsx"]],
  ["officeimo-csv", "csv/index.js", ["core", "csv"]],
  ["officeimo-pdf", "pdf/index.js", ["core", "pdf"]],
  ["officeimo-execution", "execution/index.js", []],
  ["officeimo-datatables", "integrations/datatables/index.js", [], true],
  ["officeimo-canopyx", "integrations/canopyx/index.js", [], true]
];

function bindings(text) {
  return text.split(",").map(s => s.trim()).filter(Boolean).map(s => {
    const match = /^(\w+)(?:\s+as\s+(\w+))?$/.exec(s);
    if (!match) throw new Error("Unsupported module binding: " + s);
    return { source: match[1], name: match[2] ?? match[1] };
  });
}

// tsc emits neither template literals nor line continuations here, so every line break and leading space sits
// outside a literal. Refuse to compact anything else instead of risking a changed string.
function compact(source, path) {
  if (source.includes("`") || /\\\n/.test(source)) throw new Error("Cannot safely compact " + path + ": template literal or line continuation.");
  return source.split("\n").map(line => line.trim()).filter(Boolean).join("\n");
}

// Parse one graph. Modules listed in `shared` are referenced from the shared writer core instead of being embedded.
async function parse(entry, minified, shared) {
  const modules = new Map(), ordered = [], visiting = new Set(), external = [];
  async function visit(path) {
    if (visiting.has(path)) throw new Error("Classic graph must be acyclic: " + relative(dist, path));
    if (modules.has(path)) return modules.get(path);
    if (!path.startsWith(dist + "/") && !path.startsWith(dist + "\\")) throw new Error("Module escaped dist.");
    const provided = shared?.get(path);
    if (provided) {
      const module = { id: "_c" + external.length, exports: provided.exports, key: provided.key, path };
      modules.set(path, module); external.push(module); return module;
    }
    const module = { id: "_m" + modules.size, exports: new Map(), source: "", key: "", path };
    modules.set(path, module); visiting.add(path);
    const readable = (await readFile(path, "utf8")).replace(/\r\n/g, "\n");
    const identity = createHash("sha256").update(relative(dist, path).replace(/\\/g, "/") + "\n" + readable);
    let source = minified ? compact((await readFile(join(distMin, relative(dist, path)), "utf8")).replace(/\r\n/g, "\n"), path) : readable;
    const references = [...source.matchAll(/^(import|export)\s+(\{[^}]*\}|\* as \w+)\s+from\s+"([^"]+)";\s*$/gm)];
    for (const match of references) {
      const [, kind, clause, specifier] = match;
      if (!specifier.startsWith(".")) throw new Error("Runtime dependency is forbidden: " + specifier);
      const dependency = await visit(resolve(dirname(path), specifier));
      identity.update("\n" + dependency.key);
      let replacement = "";
      if (clause.startsWith("* as ")) {
        if (kind !== "export") throw new Error("Unsupported namespace import.");
        module.exports.set(clause.slice(5), dependency.id);
      } else {
        const list = bindings(clause.slice(1, -1));
        for (const binding of list) if (!dependency.exports.has(binding.source)) throw new Error("Unknown export " + binding.source + " from " + specifier);
        if (kind === "import") replacement = "const { " + list.map(b => b.source === b.name ? b.name : b.source + ": " + b.name).join(", ") + " } = " + dependency.id + ";";
        else for (const binding of list) module.exports.set(binding.name, dependency.id + "." + binding.source);
      }
      source = source.replace(match[0], replacement + "\n");
    }
    source = source.replace(/^export\s+((?:async\s+)?function\*?|class|const|let)\s+(\w+)/gm, (_, declaration, symbol) => {
      module.exports.set(symbol, symbol); return declaration + " " + symbol;
    }).replace(/^export\s*\{([^}]*)\};\s*$/gm, (_, list) => {
      for (const b of bindings(list)) module.exports.set(b.name, b.source);
      return "";
    });
    if (/^\s*(?:import|export)\b/m.test(source)) throw new Error("Unsupported module syntax in " + relative(dist, path));
    module.source = minified ? source.split("\n").filter(Boolean).join("\n") : source.trimEnd();
    module.key = identity.digest("hex");
    visiting.delete(path); ordered.push(module); return module;
  }
  const main = await visit(join(dist, entry));
  return { main, ordered, modules, external, visit };
}

// Same spacing rules as the CanopyX asset build, which already applies them to the published CanopyX integration bundle.
// Quoted text stays as written, and a slash keeps the rest of its line and the following line break, whether it starts
// a regex or a division. Lines join only after a delimiter that cannot end an ASI statement, or before a closer.
function compactSpacing(content) {
  const literal = /("(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|\/.*)/;
  let result = "", previous = "", slash = false;
  for (const line of content.split("\n")) {
    const pieces = line.split(literal);
    for (let i = 0; i < pieces.length; i += 2) {
      pieces[i] = pieces[i].replace(/\s*([=(){},;[\]<>!&|?:%*^])\s*/g, "$1")
        // A spaced + or - joins its operands unless a neighbour is another + or -, which would form ++ or --.
        .replace(/(?<![+\-\s])\s+([+\-])\s+(?![+\-\s])/g, "$1")
        // A closing brace ends the statement before it.
        .replaceAll(";}", "}");
    }
    const compacted = pieces.join("");
    if (result && (slash || (!/[;,{([]$/.test(previous) && !/^[)}\]]/.test(compacted)))) result += "\n";
    else if (result && compacted.startsWith("}") && previous.endsWith(";")) result = result.slice(0, -1);
    result += compacted; previous = compacted;
    slash = pieces.some(piece => piece.startsWith("/"));
  }
  return result;
}

function graph(ordered, cached) {
  return ordered.map(m => "const " + m.id + " = " + (cached ? '_modules.get("' + m.key + '") ?? ' : "") +
    "(() => {\n" + m.source + "\nconst _exports = Object.freeze({ " +
    [...m.exports].map(([key, value]) => key + ": " + value).join(", ") + " });\n" +
    (cached ? '_modules.set("' + m.key + '", _exports);\n' : "") + "return _exports;\n})();").join("\n\n");
}

const outputs = new Map();
for (const minified of [false, true]) {
  const suffix = minified ? ".min" : "", emit = (file, content) => outputs.set(file, minified ? compactSpacing(content) : content);
  const parsed = new Map();
  for (const [name, entry, namespaces] of bundles) {
    const result = await parse(entry, minified);
    result.namespaces = [];
    for (const ns of namespaces) result.namespaces.push([ns, await result.visit(join(dist, ns, "index.js"))]);
    parsed.set(name, result);
  }
  // Adapters: the integration graph minus every module the shared core already carries.
  const coreGraph = parsed.get(core);
  const adapters = [], registry = new Map();
  for (const [name, entry, , adapter] of bundles) {
    if (!adapter) continue;
    const result = await parse(entry, minified, coreGraph.modules);
    for (const m of result.external) registry.set(m.key, coreGraph.modules.get(m.path).id);
    adapters.push([name, result]);
  }
  const prelude = '(function (root) {\n"use strict";\nconst officeimo = root.OfficeIMO || (root.OfficeIMO = {});\n' +
    'const cacheKey = Symbol.for("' + cacheSymbol + '");\n';
  // Standalone scripts reuse identical modules, including error/model class identities.
  // Hashing source and dependency identities prevents mixing different module versions.
  for (const [name, { main, ordered, namespaces }] of parsed) {
    const fields = [...main.exports.keys()];
    const classic = banner + prelude +
      'const _modules = officeimo[cacheKey] || new Map();\n' +
      'if (!officeimo[cacheKey]) Object.defineProperty(officeimo, cacheKey, { value: _modules });\n' + graph(ordered, true) + "\nObject.assign(officeimo, " + main.id +
      (namespaces.length ? ", { " + namespaces.map(([key, m]) => key + ": " + m.id).join(", ") + " }" : "") + ");\n})(globalThis);\n";
    // The shared core also hands the modules its adapters reference to the ES module adapters of the same build.
    const shares = name === core ? [...registry] : [];
    const esm = banner + graph(ordered, false) + "\n" +
      (shares.length ? "const " + registryName + " = Object.freeze({ " + shares.map(([key, id]) => '"' + key + '": ' + id).join(", ") + " });\n" : "") +
      "const { " + fields.join(", ") + " } = " + main.id + ";\nexport { " + [...fields, ...(shares.length ? [registryName] : [])].join(", ") + " };\n";
    emit(name + suffix + ".js", classic); emit(name + suffix + ".mjs", esm);
  }
  for (const [name, { main, ordered, external }] of adapters) {
    const fields = [...main.exports.keys()], file = name + "-adapter" + suffix;
    const lookup = (table, extension) => "const _core = key => { const value = " + table + "; if (!value) throw new Error(\"" + file + extension + " needs " +
      core + extension + " or " + core + ".min" + extension + " from the same OfficeIMO build, loaded first.\"); return value; };\n" +
      external.map(m => "const " + m.id + ' = _core("' + m.key + '");').join("\n") + "\n";
    const classic = banner + prelude + "const _modules = officeimo[cacheKey];\n" + lookup("_modules && _modules.get(key)", ".js") +
      graph(ordered, true) + "\nObject.assign(officeimo, " + main.id + ");\n})(globalThis);\n";
    const esm = banner + "import { " + registryName + ' } from "./' + core + suffix + '.mjs";\n' + lookup(registryName + "[key]", ".mjs") +
      graph(ordered, false) + "\nconst { " + fields.join(", ") + " } = " + main.id + ";\nexport { " + fields.join(", ") + " };\n";
    emit(file + ".js", classic); emit(file + ".mjs", esm);
  }
}

for (const [file, content] of outputs) {
  const path = join(output, file);
  if (check) {
    let actual;
    try { actual = await readFile(path, "utf8"); } catch { /* missing is stale too */ }
    if (actual !== content) throw new Error("Stale bundle " + file + "; run npm run build and commit it.");
  } else await writeFile(path, content, "utf8");
}
