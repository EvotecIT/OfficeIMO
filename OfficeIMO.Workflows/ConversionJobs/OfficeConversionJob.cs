using System.Text.Json.Serialization;

namespace OfficeIMO.Workflows;

/// <summary>A portable, local conversion batch. Paths resolve against the job file's directory, never the process directory.</summary>
public sealed class OfficeConversionJob {
    /// <summary>The supported saved-job schema.</summary>
    public const string CurrentSchema = "officeimo.conversion.job.v1";
    /// <summary>Versioned contract identifier.</summary>
    [JsonRequired]
    public string Schema { get; set; } = CurrentSchema;
    /// <summary>Optional display name.</summary>
    public string? Name { get; set; }
    /// <summary>Source folder, relative to the job file or absolute.</summary>
    public string? InputDirectory { get; set; }
    /// <summary>Explicit source files. A source folder, when supplied, defines their relative output layout.</summary>
    public string[]? InputPaths { get; set; }
    /// <summary>Destination folder, relative to the job file or absolute.</summary>
    public string OutputDirectory { get; set; } = string.Empty;
    /// <summary>Destination extension. Defaults to PDF.</summary>
    public string TargetExtension { get; set; } = ".pdf";
    /// <summary>Optional exact route from the configured host's conversion catalog.</summary>
    public string? ConversionRouteId { get; set; }
    /// <summary>Whether to discover source subfolders.</summary>
    public bool Recursive { get; set; } = true;
    /// <summary>Optional source-extension filter.</summary>
    public string[]? SourceExtensions { get; set; }
    /// <summary>Cross-format output intent.</summary>
    public OfficeWorkflowOutputProfile OutputProfile { get; set; } = OfficeWorkflowOutputProfile.Faithful;
    /// <summary>Existing destination behavior. Checkpoints require Fail.</summary>
    public OfficeWorkflowConflictPolicy ConflictPolicy { get; set; } = OfficeWorkflowConflictPolicy.Fail;
    /// <summary>Optional separate durable state folder.</summary>
    public string? CheckpointDirectory { get; set; }
    /// <summary>Whether recorded failed items may execute again.</summary>
    public bool RetryFailed { get; set; }
    /// <summary>Concurrent conversions, from one through 32.</summary>
    public int MaximumConcurrency { get; set; } = 2;
    /// <summary>Maximum discovered files, including skipped files.</summary>
    public int MaximumFiles { get; set; } = 1_000_000;
    /// <summary>Maximum source bytes per file.</summary>
    public long MaximumInputBytes { get; set; } = 64L * 1024 * 1024;
    /// <summary>Maximum generated bytes per file.</summary>
    public long MaximumOutputBytes { get; set; } = 256L * 1024 * 1024;
    /// <summary>Maximum XML characters per source part.</summary>
    public long MaximumXmlCharactersInPart { get; set; } = 10L * 1024 * 1024;
    /// <summary>Portable renderer choices. Advanced native renderer objects remain runtime API settings.</summary>
    public OfficeConversionJobOptions Options { get; set; } = new();
    /// <summary>Runtime secret references. Values are never saved in a job.</summary>
    public OfficeConversionJobSecrets Secrets { get; set; } = new();

    /// <summary>Creates independent absolute-path execution settings. Secrets are resolved only when runtime options are supplied.</summary>
    public OfficeConversionBatchRequest CreateRequest(string baseDirectory, OfficeConversionJobRuntimeOptions? runtime = null) {
        OfficeConversionJobSerializer.Validate(this);
        if (!Path.IsPathFullyQualified(baseDirectory)) throw new ArgumentException("The job base directory must be absolute.", nameof(baseDirectory));
        string Resolve(string path) => Path.GetFullPath(path, baseDirectory);
        var options = Options.CreateOptions();
        string? ResolveSecret(string? reference) {
            if (reference == null || runtime == null) return null;
            string? value = runtime.ResolveEnvironmentVariable?.Invoke(reference);
            return string.IsNullOrEmpty(value) ? throw new InvalidOperationException("The job requires an admitted runtime secret: " + reference) : value;
        }
        options.SourcePassword = ResolveSecret(Secrets.SourcePasswordEnvironmentVariable);
        return new OfficeConversionBatchRequest {
            InputDirectory = InputDirectory == null ? null : Resolve(InputDirectory),
            InputPaths = InputPaths?.Select(Resolve).ToArray(), OutputDirectory = Resolve(OutputDirectory),
            TargetExtension = TargetExtension, ConversionRouteId = ConversionRouteId,
            Recursive = Recursive, SourceExtensions = SourceExtensions?.ToArray(), OutputProfile = OutputProfile,
            ConflictPolicy = ConflictPolicy, CheckpointDirectory = CheckpointDirectory == null ? null : Resolve(CheckpointDirectory),
            RetryFailed = RetryFailed, MaximumConcurrency = MaximumConcurrency, MaximumFiles = MaximumFiles,
            MaximumInputBytes = MaximumInputBytes, MaximumOutputBytes = MaximumOutputBytes,
            MaximumXmlCharactersInPart = MaximumXmlCharactersInPart, ConversionOptions = options,
            PdfPassword = ResolveSecret(Secrets.PdfPasswordEnvironmentVariable)
        };
    }

    /// <summary>Captures supported settings using paths relative to an absolute job directory. Runtime passwords and advanced settings are rejected.</summary>
    public static OfficeConversionJob FromRequest(OfficeConversionBatchRequest request, string baseDirectory) {
        ArgumentNullException.ThrowIfNull(request);
        if (!Path.IsPathFullyQualified(baseDirectory)) throw new ArgumentException("The job base directory must be absolute.", nameof(baseDirectory));
        if (string.IsNullOrWhiteSpace(request.OutputDirectory) || request.InputDirectory != null && string.IsNullOrWhiteSpace(request.InputDirectory) ||
            request.CheckpointDirectory != null && string.IsNullOrWhiteSpace(request.CheckpointDirectory) ||
            request.InputPaths?.Any(string.IsNullOrWhiteSpace) == true)
            throw new ArgumentException("Job paths must not be empty.", nameof(request));
        ArgumentNullException.ThrowIfNull(request.ConversionOptions);
        if (request.PdfPassword != null || request.ConversionOptions.SourcePassword != null)
            throw new NotSupportedException("Saved jobs require password environment-variable references, never password values.");
        string Relative(string path) => Path.GetRelativePath(baseDirectory, Path.GetFullPath(path, baseDirectory));
        var job = new OfficeConversionJob {
            InputDirectory = request.InputDirectory == null ? null : Relative(request.InputDirectory),
            InputPaths = request.InputPaths?.Select(Relative).ToArray(), OutputDirectory = Relative(request.OutputDirectory),
            TargetExtension = request.TargetExtension, ConversionRouteId = request.ConversionRouteId,
            Recursive = request.Recursive, SourceExtensions = request.SourceExtensions?.ToArray(),
            OutputProfile = request.OutputProfile, ConflictPolicy = request.ConflictPolicy,
            CheckpointDirectory = request.CheckpointDirectory == null ? null : Relative(request.CheckpointDirectory),
            RetryFailed = request.RetryFailed, MaximumConcurrency = request.MaximumConcurrency, MaximumFiles = request.MaximumFiles,
            MaximumInputBytes = request.MaximumInputBytes, MaximumOutputBytes = request.MaximumOutputBytes,
            MaximumXmlCharactersInPart = request.MaximumXmlCharactersInPart,
            Options = OfficeConversionJobOptions.Capture(request.ConversionOptions)
        };
        OfficeConversionJobSerializer.Validate(job);
        return job;
    }
}

/// <summary>Names of environment variables admitted by the executing host. Values are not part of the saved contract.</summary>
public sealed class OfficeConversionJobSecrets {
    /// <summary>Variable supplying an encrypted Office source password.</summary>
    public string? SourcePasswordEnvironmentVariable { get; set; }
    /// <summary>Variable supplying a PDF source password.</summary>
    public string? PdfPasswordEnvironmentVariable { get; set; }
}

/// <summary>Execution-only host services. Planning does not invoke this resolver.</summary>
public sealed class OfficeConversionJobRuntimeOptions {
    /// <summary>Resolves only environment-variable names admitted by this host; null means unavailable.</summary>
    public Func<string, string?>? ResolveEnvironmentVariable { get; set; }
}
