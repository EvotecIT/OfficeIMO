namespace OfficeIMO;

/// <summary>Shared horizontal alignment for document text and content.</summary>
public enum OfficeAlignment {
    /// <summary>Aligns to the left edge.</summary>
    Left,
    /// <summary>Centers between the edges.</summary>
    Center,
    /// <summary>Aligns to the right edge.</summary>
    Right,
    /// <summary>Distributes words across the line.</summary>
    Justify,
    /// <summary>Aligns to the logical start edge for the content direction.</summary>
    Start,
    /// <summary>Aligns to the logical end edge for the content direction.</summary>
    End
}
